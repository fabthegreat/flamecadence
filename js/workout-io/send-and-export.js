// --- ERG / MRC : points « minutes valeur » (rampes = deux points, paliers = saut vertical) ---
function buildErgPoints(steps, val){
  const rows = []; let t = 0;
  steps.forEach(s => { rows.push(t.toFixed(2) + "\t" + val(s.a, s.aw)); t += s.d / 60; rows.push(t.toFixed(2) + "\t" + val(s.b, s.bw)); });
  return rows;
}
function ergHeader(kind, fname, desc){
  return `[COURSE HEADER]\nVERSION = 2\nUNITS = ENGLISH\nDESCRIPTION = ${desc}\nFILE NAME = ${fname}\nMINUTES ${kind === "mrc" ? "PERCENT" : "WATTS"}\n[END]\n[COURSE DATA]\n`;
}
function buildErg(steps){
  const ftp = curFtp(), name = ($("name").value || "workout").trim();
  return ergHeader("erg", expFname(".erg"), name) + buildErgPoints(steps, (p, w) => w != null ? Math.round(w) : Math.round(p * ftp / 100)).join("\n") + "\n[END]";
}
function buildMrc(steps){
  const name = ($("name").value || "workout").trim();
  return ergHeader("mrc", expFname(".mrc"), name) + buildErgPoints(steps, p => p.toFixed(1)).join("\n") + "\n[END]";
}
function buildJson(steps){
  return JSON.stringify({
    name: ($("name").value || "Workout").trim(),
    sport: $("sport").value,
    ftp: curFtp(),
    description: $("desc").value,
    steps: steps.map((s, i) => ({index: i, duration_s: Math.round(s.d), from_pct: Math.round(s.a * 10) / 10, to_pct: Math.round(s.b * 10) / 10}))
  }, null, 2);
}
