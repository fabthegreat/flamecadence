const BRAND = "Generated by FlameCadence (flamecadence.lutix.org)";
function stripBrand(desc, name){
  const L = String(desc || "").replace(/\r/g, "").split("\n");
  while(L.length && !L[L.length - 1].trim()) L.pop();
  if(L.length && /^generated by flamecadence\b/i.test(L[L.length - 1].trim())) L.pop();
  while(L.length && !L[L.length - 1].trim()) L.pop();
  const nm = String(name || "").trim();
  if(nm && L.length > 1 && L[0].trim() === nm && !L[1].trim()){ L.shift(); while(L.length && !L[0].trim()) L.shift(); }
  return L.join("\n");
}
function brandDesc(name, desc){
  const nm = String(name || "").trim(), body = stripBrand(desc, nm).trim();
  return (nm ? nm + "\n\n" : "") + body + "\n\n" + BRAND;
}
