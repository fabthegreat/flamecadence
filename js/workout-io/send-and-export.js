function buildZwo(steps){
  const body = steps.map(s => {
    const dur = Math.round(s.d), lo = Math.min(s.a, s.b) / 100, hi = Math.max(s.a, s.b) / 100;
    if(Math.abs(s.a - s.b) > 0.5) return `<${lo < hi ? "Warmup" : "Cooldown"} Duration="${dur}" PowerLow="${lo.toFixed(3)}" PowerHigh="${hi.toFixed(3)}"/>`;
    return `<SteadyState Duration="${dur}" Power="${(s.a / 100).toFixed(3)}"/>`;
  }).join("\n      ");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<workout_file>\n  <author>FlameCadence</author>\n  <name>${esc(($("name").value || "Workout").trim())}</name>\n  <workout>\n      ${body}\n  </workout>\n</workout_file>`;
}
// --- FIT binaire (workout) ---
function fitCrc(bytes){ // CRC-16 du SDK FIT (CRC-16/ARC, algorithme à quartets) — et non CRC-CCITT
  const T = [0x0000, 0xCC01, 0xD801, 0x1400, 0xF001, 0x3C00, 0x2800, 0xE401, 0xA001, 0x6C00, 0x7800, 0xB401, 0x5000, 0x9C01, 0x8801, 0x4400];
  let crc = 0;
  for(const b of bytes){
    crc = (crc >> 4 & 0x0FFF) ^ T[crc & 0xF] ^ T[b & 0xF];
    crc = (crc >> 4 & 0x0FFF) ^ T[crc & 0xF] ^ T[b >> 4 & 0xF];
  }
  return crc;
}
function fitDef(local, global, fields){
  const b = [0x40 | local, 0, 0, global & 0xff, (global >> 8) & 0xff, fields.length];
  fields.forEach(([n, s, t]) => b.push(n, s, t));
  return b;
}
const u16 = v => [v & 0xff, (v >> 8) & 0xff];
const u32 = v => [v & 0xff, (v >> 8) & 0xff, (v >> 16) & 0xff, (v >>> 24) & 0xff];
function buildFit(steps){
  const str = (s, n) => { const b = []; for(let i = 0; i < n; i++) b.push(i < s.length ? s.charCodeAt(i) & 0xff : 0); return b; };
  const pad4 = n => Math.min(64, (Math.floor(n / 4) + 1) * 4); // chaîne FIT : multiple de 4 recommandé
  const name = ($("name").value || "Workout").trim().slice(0, 40), nameLen = pad4(name.length + 1);
  const ts = Math.floor(Date.now() / 1000) - 631065600; // epoch FIT : 31/12/1989
  const records = [];
  // file_id (local 0) : time(4,u32), manufacturer(1,u16), product(2,u16), serial(3,u32), type(0,enum)
  records.push(fitDef(0, 0, [[4, 4, 134], [1, 2, 132], [2, 2, 132], [3, 4, 134], [0, 1, 0]]));
  records.push([0, ...u32(ts), ...u16(255), ...u16(0), ...u32(ts), 5]);
  // workout (local 1) : sport(0,enum), num_valid_steps(5,u16), wkt_name(6,string), sub_sport(11,enum)
  records.push(fitDef(1, 26, [[0, 1, 0], [5, 2, 132], [6, nameLen, 7], [11, 1, 0]]));
  records.push([1, isBike($("sport").value) ? 2 : 1, ...u16(steps.length), ...str(name, nameLen), 0]);
  // workout_step (local 2) : message_index(254,u16), duration_type(0,enum), duration_value(1,u32),
  // target_type(2,enum), target_value(3,u32), custom_target_value_low(5,u32), custom_target_value_high(6,u32), intensity(7,enum)
  records.push(fitDef(2, 27, [[254, 2, 132], [0, 1, 0], [1, 4, 134], [2, 1, 0], [3, 4, 134], [5, 4, 134], [6, 4, 134], [7, 1, 0]]));
  steps.forEach((s, i) => {
    const mid = (s.a + s.b) / 2;
    let intensity = 0; // active
    if(i === 0 && mid < 76) intensity = 2; // warmup
    else if(i === steps.length - 1 && mid < 76) intensity = 3; // cooldown
    else if(mid < 56) intensity = 1; // rest
    const pm = Math.max(0, Math.min(1000, Math.round(mid * 10))); // puissance relative 0..1000 pour mille
    records.push([2, ...u16(i), 0, ...u32(Math.round(s.d) * 1000), 4, ...u32(0), ...u32(pm), ...u32(pm), intensity]);
  });
  const data = records.flat();
  const head = [14, 0x10, 0xB6, 0x0B, ...u32(data.length), 0x2E, 0x46, 0x49, 0x54];
  const headCrc = fitCrc(head);
  const file = [...head, headCrc & 0xff, (headCrc >> 8) & 0xff, ...data];
  const crc = fitCrc(file);
  file.push(crc & 0xff, (crc >> 8) & 0xff);
  return file;
}
// --- FIT binaire (activité enregistrée) : file_id, event, record (puissance, FC, cadence, distance, vitesse, altitude), lap, session, activity ---
// pts : [{t: secondes epoch, p: W, h: bpm, c: rpm, d: mètres cumulés, s: m/s, a: altitude m}] ; o : {sport, sub, name}
function buildActFit(pts, o){
  o = o || {};
  const FT = x => Math.max(0, Math.round(x) - 631065600), cl = (v, mx) => Math.max(0, Math.min(mx, Math.round(v)));
  const ok = v => v != null && isFinite(v);
  const b8 = v => ok(v) ? cl(v, 254) : 0xFF, b16 = v => ok(v) ? cl(v, 65534) : 0xFFFF, b32 = v => ok(v) ? cl(v, 4294967294) : 0xFFFFFFFF;
  const avg = a => a.length ? a.reduce((x, y) => x + y, 0) / a.length : null, mx = a => a.length ? Math.max(...a) : null;
  const t0 = pts[0].t, t1 = pts[pts.length - 1].t, dur = Math.max(1, t1 - t0), ms = Math.round(dur * 1000);
  const P = pts.filter(x => ok(x.p)).map(x => x.p), H = pts.filter(x => ok(x.h) && x.h > 0).map(x => x.h), C = pts.filter(x => ok(x.c)).map(x => x.c);
  
  const sport = o.sport != null ? o.sport : 2, sub = o.sub != null ? o.sub : 0;
  const rec = [];
  // file_id (0) : type(0)=4 activité, manufacturer(1)=255 développement, product(2), serial_number(3), time_created(4)
  rec.push(fitDef(0, 0, [[0, 1, 0], [1, 2, 132], [2, 2, 132], [3, 4, 140], [4, 4, 134]]));
  rec.push([0, 4, ...u16(255), ...u16(0), ...u32(FT(t0)), ...u32(FT(t0))]);
  // event (21) : timestamp(253), event(0)=0 minuteur, event_type(1)=0 démarrage / 4 arrêt
  rec.push(fitDef(1, 21, [[253, 4, 134], [0, 1, 0], [1, 1, 0]]));
  rec.push([1, ...u32(FT(t0)), 0, 0]);
  // record (20) : seuls les champs réellement présents sont déclarés (aucune valeur « invalide »), distance et vitesse toujours renseignées et croissantes
  const hasH = pts.some(x => ok(x.h) && x.h > 0), hasP = pts.some(x => ok(x.p)), hasC = pts.some(x => ok(x.c)), hasA = pts.some(x => ok(x.a));
  const rf = [[253, 4, 134]]; if(hasH) rf.push([3, 1, 2]); if(hasC) rf.push([4, 1, 2]); rf.push([5, 4, 134], [6, 2, 132]); if(hasP) rf.push([7, 2, 132]); if(hasA) rf.push([2, 2, 132]);
  rec.push(fitDef(2, 20, rf));
  // sortie home trainer sans vitesse ni distance : Strava n'affiche alors aucune courbe (graphes tracés sur la distance) ; on estime une vitesse « virtuelle »
  // à partir de la puissance (route plate, 85 kg rider + vélo, Crr 0,004, CdA 0,35 m², rendement 97,5 %), comme le font les applis d'entraînement virtuel
  const virt = sport === 2 && pts.some(x => ok(x.p) && x.p > 0) && !pts.some(x => ok(x.d) && x.d > 0) && !pts.some(x => ok(x.s) && x.s > 0);
  const vOf = pw => { const P = pw * 0.975; if(!(P > 0)) return 0; let lo = 0, hi = 30; for(let k = 0; k < 40; k++){ const v = (lo + hi) / 2; (v * (0.004 * 85 * 9.81 + 0.5 * 1.2 * 0.35 * v * v) > P ? hi = v : lo = v); } return lo; };
  let lastT = -1, dAcc = 0, lastD = 0, ph = 0, pc = 0, pa = 500;
  pts.forEach((x, i) => {
    let ts = FT(x.t); if(ts <= lastT) ts = lastT + 1; const dt = lastT < 0 ? 0 : ts - lastT; lastT = ts;
    let sp = virt ? vOf(ok(x.p) ? x.p : 0) : ok(x.s) ? Math.max(0, x.s) : null;
    if(ok(x.d)){ dAcc = Math.max(dAcc, x.d); if(sp == null) sp = dt > 0 ? Math.max(0, (dAcc - lastD) / dt) : 0; } else dAcc += (sp || 0) * dt;
    lastD = dAcc; if(sp == null) sp = 0;
    if(ok(x.h) && x.h > 0) ph = x.h; if(ok(x.c)) pc = x.c; if(ok(x.a)) pa = x.a;
    rec.push([2, ...u32(ts), ...(hasH ? [cl(ph, 254)] : []), ...(hasC ? [cl(pc, 254)] : []), ...u32(cl(dAcc * 100, 4294967294)), ...u16(cl(sp * 1000, 65534)), ...(hasP ? u16(cl(ok(x.p) ? x.p : 0, 65534)) : []), ...(hasA ? u16(cl((pa + 500) * 5, 65534)) : [])]);
  });
  const dist2 = dAcc;
  rec.push([1, ...u32(FT(t1)), 0, 4]);
  // lap (19) : timestamp(253), event(0)=9, event_type(1)=1, start_time(2), total_elapsed_time(7), total_timer_time(8), total_distance(9), avg_heart_rate(15), max_heart_rate(16), avg_cadence(17), avg_power(19), max_power(20), sport(25), sub_sport(39)
  const tot = [[7, 4, 134], [8, 4, 134], [9, 4, 134]];
  rec.push(fitDef(3, 19, [[253, 4, 134], [0, 1, 0], [1, 1, 0], [2, 4, 134], ...tot, [15, 1, 2], [16, 1, 2], [17, 1, 2], [19, 2, 132], [20, 2, 132], [25, 1, 0], [39, 1, 0]]));
  rec.push([3, ...u32(FT(t1)), 9, 1, ...u32(FT(t0)), ...u32(ms), ...u32(ms), ...u32(cl(dist2 * 100, 4294967294)), b8(avg(H)), b8(mx(H)), b8(avg(C)), ...u16(b16(avg(P))), ...u16(b16(mx(P))), sport, sub]);
  // session (18) : timestamp(253), message_index(254), event(0)=8, event_type(1)=1, start_time(2), sport(5), sub_sport(6), totaux(7,8,9), first_lap_index(25), num_laps(26), avg_heart_rate(16), max_heart_rate(17), avg_cadence(18), avg_power(20), max_power(21)
  rec.push(fitDef(4, 18, [[253, 4, 134], [254, 2, 132], [0, 1, 0], [1, 1, 0], [2, 4, 134], [5, 1, 0], [6, 1, 0], ...tot, [25, 2, 132], [26, 2, 132], [16, 1, 2], [17, 1, 2], [18, 1, 2], [20, 2, 132], [21, 2, 132]]));
  rec.push([4, ...u32(FT(t1)), ...u16(0), 8, 1, ...u32(FT(t0)), sport, sub, ...u32(ms), ...u32(ms), ...u32(cl(dist2 * 100, 4294967294)), ...u16(0), ...u16(1), b8(avg(H)), b8(mx(H)), b8(avg(C)), ...u16(b16(avg(P))), ...u16(b16(mx(P)))]);
  // activity (34) : timestamp(253), total_timer_time(0), num_sessions(1), type(2)=0, event(3)=26, event_type(4)=1
  rec.push(fitDef(5, 34, [[253, 4, 134], [0, 4, 134], [1, 2, 132], [2, 1, 0], [3, 1, 0], [4, 1, 0]]));
  rec.push([5, ...u32(FT(t1)), ...u32(ms), ...u16(1), 0, 26, 1]);
  const data = rec.flat();
  const head = [14, 0x10, 0xB6, 0x0B, ...u32(data.length), 0x2E, 0x46, 0x49, 0x54], hc = fitCrc(head);
  const file = [...head, hc & 0xff, (hc >> 8) & 0xff, ...data], crc = fitCrc(file);
  file.push(crc & 0xff, (crc >> 8) & 0xff);
  return Uint8Array.from(file);
}
